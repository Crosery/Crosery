SPACE = 8  # advance for a space, in art px


def glyph(ch: str) -> tuple[int, tuple[str, ...]] | None:
    if ch in CAPS:
        return CAPS[ch]
    return LOWER.get(ch.lower())


def render(text: str) -> tuple[list[tuple[int, int]], int, int] | None:
    """Filled pixels of `text` plus (width, height), or None if a glyph is missing."""
    cells: list[tuple[int, int]] = []
    x = 0
    for ch in text:
        if ch == " ":
            x += SPACE
            continue
        g = glyph(ch)
        if g is None:
            return None
        top, rows = g
        for j, row in enumerate(rows):
            for i, c in enumerate(row):
                if c == "#":
                    cells.append((x + i, top + j))
        x += len(rows[0]) + GAP
    if not cells:
        return None
    return cells, x - GAP, HEIGHT
