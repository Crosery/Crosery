LETTERS = (C, R, O, S, E, R, Y)
BASELINE = 22  # rows from the top of the tallest letter (C) to the baseline
X_HEIGHT = 16
DESCENT = 6


def size() -> tuple[int, int]:
    w = sum(len(letter[0]) for letter in LETTERS) + GAP * (len(LETTERS) - 1)
    return w, BASELINE + DESCENT


def cells() -> list[tuple[int, int]]:
    """(x, y) of every filled pixel, relative to the wordmark's top-left."""
    out: list[tuple[int, int]] = []
    x = 0
    for letter in LETTERS:
        h = len(letter)
        # letters sit on the shared baseline; the y hangs its descender below it
        top = (
            BASELINE - X_HEIGHT if h in (X_HEIGHT, X_HEIGHT + DESCENT) else BASELINE - h
        )
        for j, row in enumerate(letter):
            for i, ch in enumerate(row):
                if ch == "#":
                    out.append((x + i, top + j))
        x += len(letter[0]) + GAP
    return out
